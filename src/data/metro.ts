export function stationPos(name: string): [number, number] {
  return OSM_METRO_STATIONS[name] ?? [350, 200];
}

/** Назва для показу (без модифікатора апострофа, якого немає в шрифті). */
export function stationLabel(name: string): string {
  return name.replace(/ʼ/g, '’');
}
